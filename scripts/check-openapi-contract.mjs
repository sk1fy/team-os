import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const args = process.argv.slice(2);
const write = args.includes('--write');
const contractArgument = args.find((argument) => !argument.startsWith('--'));
const contractPath = resolve(
  process.cwd(),
  contractArgument ??
    process.env.OPENAPI_CONTRACT ??
    '../team-os-backend/contracts/openapi/teamos.yaml',
);
const generatedPath = resolve(process.cwd(), 'src/api/generated/teamos.ts');
const header = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

`;

const nodes = await openapiTS(pathToFileURL(contractPath));
const expected = header + astToString(nodes);

if (write) {
  await mkdir(dirname(generatedPath), { recursive: true });
  await writeFile(generatedPath, expected);
  console.log(`OpenAPI types updated from ${contractPath}`);
  process.exit(0);
}

const actual = await readFile(generatedPath, 'utf8').catch(() => '');
if (actual !== expected) {
  console.error('Generated OpenAPI types are stale.');
  console.error(`Run: npm run contract:generate -- ${contractPath}`);
  process.exit(1);
}

console.log(`OpenAPI schema matches ${contractPath}`);
